@pytest.fixture
def db_case(monkeypatch):
    assert settings.order_db_dsn, 'ORDER_DB_DSN is required'
    db = MySqlCommerceDAO(settings.order_db_dsn)
    db.ensure_schema()
    identity = 'tools-test-' + uuid4().hex[:12]
    order_id = 'ORD-T-' + uuid4().hex
    sku = 'SKU-T-' + uuid4().hex[:12]
    at = datetime.now(timezone.utc)
    order = {'order_id': order_id, 'user_id': identity, 'status': 'shipped',
             'total': '129.99', 'refund_status': None}
    records = demo_records([{'product_id': sku, 'name': 'test sku', 'price': '129.99'}], [order], at)
    # Do not create/replace shared policy records; require project initialization.
    records = [r for r in records if r['kind'] != 'policies']
    # Namespace every public fixture row, including normally shared rule and
    # delivery IDs, so cleanup can never touch pre-existing demonstration data.
    for record in records:
        if not record.get('user_id'):
            record['record_id'] = sku + ':' + record['record_id']
    with db._connection() as conn:
        MySqlOrderDAO.upsert(conn, order, 'pdd')
    db.insert_seed(records)
    token = set_current_user_id(identity)
    monkeypatch.setattr('app.tools.commerce_service.database', lambda: db)
    try:
        yield db, identity, order_id, sku, at, records
    finally:
        reset_current_user_id(token)
        with db._connection() as conn, conn.cursor() as cur:
            # Every delete uses exact identifiers generated by this fixture.
            for r in records:
                cur.execute(f'DELETE FROM {TABLES[r["kind"]]} '
                            'WHERE platform_code=%s AND user_id=%s AND record_id=%s',
                            ('pdd', r.get('user_id', ''), r['record_id']))
            cur.execute('DELETE FROM commerce_invoices WHERE user_id=%s', (identity,))
            cur.execute('DELETE FROM commerce_mutations WHERE user_id=%s', (identity,))
            cur.execute("DELETE FROM orders WHERE platform_code='pdd' AND order_id=%s AND user_id=%s", (order_id, identity))
        while not db._pool.empty():
            db._pool.get_nowait().close()


def args_for_invoice(order_id):
    preview = invoke('query_invoice', {'order_id': order_id, 'mode': 'preview'})
    assert preview['success'] and preview['can_issue'], preview
    return {'order_id': order_id, 'preview_version': preview['preview_version'],
            'fields': {'title': '个人测试', 'invoice_type': 'personal'}}


def test_queries_use_mysql_contracts_and_preserve_demo_provenance(db_case):
    _, _, order_id, sku, at, _ = db_case
    offers = invoke('query_offers', {'sku_id': sku, 'channels': ['pdd', 'demo_other_shop'], 'region': '上海'})
    assert offers['source'] == 'mysql_demo' and len(offers['offers']) == 2
    assert invoke('compare_offers', {'offers': offers['offers']})['success']
    rules = invoke('query_promotions', {'sku_ids': [sku], 'channel': 'pdd'})
    assert rules['success'] and len(rules['rules']) == 1
    coupons = invoke('query_user_coupons', {})
    assert coupons['source'] == 'mysql_demo' and len(coupons['coupons']) == 1
    shipping = invoke('query_delivery_quote', {'items': [{'sku_id': sku, 'quantity': 2}], 'channel': 'pdd', 'region': '上海'})
    assert shipping['success'] and shipping['shipping_minor'] == 0
    history = invoke('query_price_history', {'sku_id': sku, 'channel': 'pdd', 'start': (at - timedelta(days=31)).isoformat(),
                                            'end': at.isoformat(), 'price_type': 'list'})
    assert history['success'] and len(history['history']['points']) == 3
    summary = invoke('summarize_price_history', {'history': history['history']})
    assert summary['lowest_observed_minor'] == 12999
    assert invoke('query_payment_status', {'order_id': order_id})['payments'][0]['amount_minor'] == 12999
    assert invoke('query_after_sale', {'order_id': order_id})['records'] == []
    action = invoke('evaluate_order_action', {'order_id': order_id, 'action': 'cancel'})
    assert action['success'] and action['can_act'] is False


